#   process_game_data_and_calculate_rewards
#####################################
def process_game_data_and_calculate_rewards(all_game_data, replay_buffer, file, calculator, logo=False):
    """
    Collect self-play game_data, calculate final rewards, and store in ReplayBuffer.
    """

    # Used to collect (factor expression, IC) pairs generated in this batch of games
    expression_ic_list = []

    for game in all_game_data:
        final_ic = 0
        final_expression = None

        # Find the terminal state by searching backward
        for step in reversed(game):
            if step[-2]:  # reached_terminal=True
                final_expression = parse_expression_from_string(step[-1].state_description())
                try:
                    final_ic = calculator.calc_single_IC_ret(final_expression)
                    if math.isnan(final_ic):
                        final_ic = 0
                    logger.info(f"{final_expression},{final_ic}")
                except OutOfDataRangeError:
                    final_ic = 0
                    logger.info(f"{final_expression}OutOfDataRangeError!")

                break

        if final_expression:
            expression_ic_list.append((final_expression, final_ic))

        # Only record if there is indeed a terminal expression
        if final_expression is not None:
            for step_idx, step in enumerate(game):
                raw_pi, current_expression, _, continue_out_game, _, _ = step
                reward = abs(final_ic) #if (step_idx == len(game) - 1) else 0
                target_policy = mcts_policy_to_target(raw_pi)
                replay_buffer.push(current_expression, target_policy, reward, continue_out_game)
                if logo:
                    with open(file, 'a', newline='', encoding='utf-8') as f:
                        writer = csv.writer(f)
                        writer.writerow([
                            target_policy,
                            reward,
                            current_expression,
                            final_expression,
                            continue_out_game
                        ])

    # Return the expressions and ICs generated in this batch of games
    return expression_ic_list


