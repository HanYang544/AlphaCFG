def self_play_game(policy_net, value_net, LEN, MCTS_SIM, MCTS_PARALLEL, BATCH_SIZE_EVAL, device=torch.device('cpu')):
    """
    Use the current policy network, value network, and MCTS to play against itself,
    returning all step data for this game.
    """
    length = 1
    continue_game = 3

    # Create initial environment state with specific actions applied
    env = AlphaEnv()
    env.reset()
    env.apply_action('binaryop', 'Mul1')
    length += 2
    env.apply_action('rollingop', 'Rank')
    length += 2
    env.apply_action('unaryop', 'CSRank')
    length += 1

    mcts = MCTS(policy_net, value_net, MCTS_SIM, MCTS_PARALLEL, BATCH_SIZE_EVAL, device)
    mcts.root = Node(state=env)
    game_data = []  # (action_probs, current_expression, coef, reached_terminal, final_state)

    # Define the length change corresponding to operator categories
    operator_length_mapping = {
        'unaryop': 1,  # Unary operators increase length by 1
        'binaryop': 2,  # Binary operators increase length by 2
        'rollingop': 2,  # Rolling operators increase length by 1
        'pairedrollingop': 3,  # Paired rolling operators increase length by 2
        'Vari': 0,  # Variables don't change length
        'constant': 0,  # Constants don't change length
        'num': 0  # Number replacements don't change length
    }

    # Loop until the expression reaches a terminal state or the cumulative length reaches the threshold
    while (not mcts.root.state.is_terminal_state()) and continue_game:
        # If the cumulative length reaches or exceeds LEN, set continue_out_game to False
        if length <= LEN - 3:
            continue_out_game = 3
        else:
            continue_out_game = LEN - length

        current_expression = mcts.root.state.state_description()
        coef = 1
        final_probas, final_move = mcts.search(competitive=False, c_puct=1, temperature=1)

        game_data.append((final_probas, current_expression, coef, continue_out_game, False, mcts.root.state))

        # Update length based on the operator category of final_move
        operator_category = final_move[0]
        length_increment = operator_length_mapping.get(operator_category, 1)
        length += length_increment

    # ---------- 2. If a terminal state is reached ----------
    if mcts.root.state.is_terminal_state():

        # 2‑a First set reached_terminal to True for all existing steps
        for i in range(len(game_data)):
            p, expr, coef, cont, _, _ = game_data[i]
            game_data[i] = (p, expr, coef, cont, True, mcts.root.state)

        # 2‑b Generate a placeholder for "terminal action_probs"  ### NEW
        first_prob = game_data[0][0] if game_data else None
        if torch.is_tensor(first_prob):
            term_probs = torch.zeros_like(first_prob)
        elif isinstance(first_prob, np.ndarray):
            term_probs = np.zeros_like(first_prob)
        elif isinstance(first_prob, dict):
            term_probs = {k: 0.0 for k in first_prob}
        else:
            raise TypeError(f"Unsupported action_probs type: {type(first_prob)}")

        # 2‑c Append the actual terminal record  ### NEW
        terminal_expr = mcts.root.state.state_description()
        coef = 1
        game_data.append((term_probs,        # All probabilities are 0
                          terminal_expr,
                          coef,
                          0,                 # No further moves allowed after terminal
                          True,              # reached_terminal
                          mcts.root.state))

    return game_data


def run_self_play(args):
    (policy_net, value_net, LEN, MCTS_SIM, MCTS_PARALLEL, BATCH_SIZE_EVAL, device, seed) = args

    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    if device.type == 'cuda':
        torch.cuda.manual_seed_all(seed)

    return self_play_game(policy_net, value_net, LEN, MCTS_SIM, MCTS_PARALLEL, BATCH_SIZE_EVAL, device)


